"""Analysis of protocol P2 (protocols/P2_cwd_confirmation.md), fixed before the runs.

    python analysis/p2_analysis.py [--out results/p2_analysis.json] [--tex paper/jmlr/generated/p2.tex]

H1: paired CWD - AdamW at S over seeds 2001-2006; t-test and bootstrap CI95 (10,000 resamples of seeds).
H2: paired differences per XS arm (R1, R4, R16) and the least-squares slope of the nine seed-level
differences against log2(epochs), with a bootstrap CI95 over seeds within arms.
H3: paired difference at M over seeds 2001-2003. H2 and H3 p-values are Holm-corrected together.
Mechanism: fraction of decayed coordinates where update and weight agree in sign (`agree` in the curves);
effective decay of CWD = wd x mean agreement fraction over the final runs.
"""
import argparse
import json
import os

import numpy as np
from scipy import stats

B = 10_000
CELLS = {'H1': 'S_D10M_E16', 'R1': 'XS_D159.384M_E1', 'R4': 'XS_D39.8459M_E4', 'R16': 'XS_D10M_E16',
         'H3': 'M_D10M_E16'}
LOG2_EPOCHS = {'R1': 0, 'R4': 2, 'R16': 4}


def load(stem, method):
    return json.load(open(f'results/dc/{stem}_{method}_p2.json'))


def boot_mean(d, rng):
    d = np.asarray(d)
    return np.percentile([d[rng.integers(0, len(d), len(d))].mean() for _ in range(B)], [2.5, 97.5]).tolist()


def mean_agree(res):
    vals = [e['agree'] for f in res['finals'].values() for e in f['curve'] if e.get('agree') is not None]
    return float(np.mean(vals)) if vals else None


def cell(stem, rng):
    c, a = load(stem, 'CWD'), load(stem, 'AdamW')
    seeds = sorted(set(c['finals']) & set(a['finals']), key=int)
    tc = np.array([c['finals'][s]['test_loss'] for s in seeds])
    ta = np.array([a['finals'][s]['test_loss'] for s in seeds])
    d = tc - ta
    t = stats.ttest_1samp(d, 0.0)
    ag = mean_agree(c)
    out = {'stem': stem, 'seeds': [int(s) for s in seeds],
           'cwd': {'winner': c['winner']['hp'], 'edge': c['winner']['edge'], 'tune_val': c['winner']['val_loss'],
                   'test': tc.tolist(), 'mean': float(tc.mean()), 'sd': float(tc.std(ddof=1)),
                   'agree': ag, 'effective_wd': ag * c['winner']['hp']['wd'] if ag is not None else None},
           'adamw': {'winner': a['winner']['hp'], 'edge': a['winner']['edge'], 'tune_val': a['winner']['val_loss'],
                     'test': ta.tolist(), 'mean': float(ta.mean()), 'sd': float(ta.std(ddof=1)),
                     'agree': mean_agree(a)},
           'diff': d.tolist(), 'diff_mean': float(d.mean()), 'diff_sd': float(d.std(ddof=1)),
           'boot_ci': boot_mean(d, rng), 't': float(t.statistic), 'p': float(t.pvalue),
           'adamw_grid': sorted(([g['hp']['lr'], g['hp']['wd'], g['val_loss']] for g in a['grid'])),
           'cwd_grid': sorted(([g['hp']['lr'], g['hp']['wd'], g['val_loss']] for g in c['grid']))}
    return out


def holm(ps):
    order = np.argsort(ps)
    adj, run = [0.0] * len(ps), 0.0
    for k, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - k) * ps[i]))
        adj[i] = run
    return adj


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default='results/p2_analysis.json')
    ap.add_argument('--tex', default='paper/jmlr/generated/p2.tex')
    args = ap.parse_args()
    rng = np.random.default_rng(0)
    res = {k: cell(v, rng) for k, v in CELLS.items()}
    h1 = res['H1']
    h1['confirmed'] = bool(h1['p'] < 0.05 and h1['boot_ci'][1] < 0)
    h1['practical'] = bool(abs(h1['diff_mean']) >= 0.03)
    # H2: slope over the nine seed-level differences
    x = np.concatenate([[LOG2_EPOCHS[a]] * len(res[a]['diff']) for a in LOG2_EPOCHS])
    y = np.concatenate([res[a]['diff'] for a in LOG2_EPOCHS])
    lr = stats.linregress(x, y)
    bs = []
    for _ in range(B):
        yb = np.concatenate([np.asarray(res[a]['diff'])[rng.integers(0, len(res[a]['diff']), len(res[a]['diff']))]
                             for a in LOG2_EPOCHS])
        bs.append(np.polyfit(x, yb, 1)[0])
    h2 = {'slope': float(lr.slope), 'p': float(lr.pvalue), 'boot_ci': np.percentile(bs, [2.5, 97.5]).tolist()}
    h2['supported'] = bool(h2['boot_ci'][1] < 0)
    p_holm = holm([h2['p'], res['H3']['p']])
    h2['p_holm'], res['H3']['p_holm'] = p_holm
    out = {'H1': h1, 'H2': {'arms': {a: res[a] for a in LOG2_EPOCHS}, **h2}, 'H3': res['H3']}
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    json.dump(out, open(args.out, 'w'), indent=1)

    rows = [('H1', 'S (51.5M)', 'R16', h1), ('H2', 'XS (30.4M)', 'R1', res['R1']),
            ('H2', 'XS (30.4M)', 'R4', res['R4']), ('H2', 'XS (30.4M)', 'R16', res['R16']),
            ('H3', 'M (124.5M)', 'R16', res['H3'])]
    L = ['% generated by analysis/p2_analysis.py; do not edit by hand',
         '\\begin{tabular}{@{}lllrllrrrcr@{}}', '\\toprule',
         'Test & Size & Arm & $n$ & CWD winner & AdamW winner & CWD & AdamW & diff & bootstrap CI95 & $p$ \\\\',
         '\\midrule']
    for h, size, arm, r in rows:
        w = lambda d: f"{d['winner']['lr']:g}, {d['winner']['wd']:g}"
        L.append(f"{h} & {size} & {arm} & {len(r['seeds'])} & {w(r['cwd'])} & {w(r['adamw'])} & "
                 f"{r['cwd']['mean']:.3f} & {r['adamw']['mean']:.3f} & ${r['diff_mean']:+.3f}$ & "
                 f"$[{r['boot_ci'][0]:+.3f}, {r['boot_ci'][1]:+.3f}]$ & {r['p']:.4f} \\\\")
    L += ['\\bottomrule', '\\end{tabular}', '']
    os.makedirs(os.path.dirname(args.tex), exist_ok=True)
    open(args.tex, 'w').write('\n'.join(L))
    print(json.dumps({'H1': {k: h1[k] for k in ('diff_mean', 'boot_ci', 'p', 'confirmed', 'practical')},
                      'H2': h2, 'H3': {k: res['H3'][k] for k in ('diff_mean', 'boot_ci', 'p', 'p_holm')},
                      'agree': {k: (round(r['cwd']['agree'], 3), round(r['cwd']['effective_wd'], 2),
                                    round(r['adamw']['agree'], 3), r['adamw']['winner']['wd'])
                                for k, r in res.items()},
                      'edges': {k: (r['cwd']['edge'], r['adamw']['edge']) for k, r in res.items()},
                      'sd': {k: (round(r['cwd']['sd'], 4), round(r['adamw']['sd'], 4), round(r['diff_sd'], 4))
                             for k, r in res.items()}}, indent=1))


if __name__ == '__main__':
    main()
