"""LaTeX appendix tables for the JMLR manuscript, from results/p1_analysis.json.

    python analysis/p1_latex_tables.py [--analysis results/p1_analysis.json] [--out paper/jmlr/generated]

Writes grids.tex (every tuning grid of every arm: tuning-seed validation loss at the best checkpoint,
rows = learning rate, columns = the second axis) and sensitivity.tex (the post-registration runs,
when present). main.tex inputs both files.
"""
import argparse
import json
import os

ARM_LABEL = {'xs_r16': 'XS, R16 (10M tokens $\\times$ 16 epochs)',
             'xs_r1': 'XS, R1 (159.4M tokens $\\times$ 1 epoch)',
             's_r16': 'S, R16 (10M tokens $\\times$ 16 epochs)'}
STEM_LABEL = {'M_D10M_E16': 'M (124.5M parameters), R16 (D = 10M x 16 epochs)',
              'S_D159.384M_E1': 'S, R1 (D = 159.4M x 1 epoch)'}
AXIS_LABEL = {'wd': 'wd', 'rho': '$\\rho$', 'ema': 'ema', 'dropout': 'dropout', 'warm_start': 'warm start',
              'delta': '$\\delta$', 'aux_lr': 'aux lr', 'aux_wd': 'aux wd', 'alpha': '$\\alpha$', 'beta3': '$\\beta_3$'}


def tex(s):
    return str(s).replace('_', '\\_').replace('%', '\\%').replace('&', '\\&')


def g(v):
    return f'{v:g}'


def hp(d):
    return ', '.join(f'{tex(k)} {g(v)}' for k, v in d.items())


def grid_table(method, grid):
    axes = [k for k in grid[0]['hp'] if k != 'lr' and len({x['hp'].get(k) for x in grid}) > 1]
    # every non-lr axis that varies is a column dimension (AdEMAMix-T varies two)
    key = lambda x: tuple(x['hp'][k] for k in axes)
    lrs = sorted({x['hp']['lr'] for x in grid})
    cols = sorted({key(x) for x in grid}) if axes else [None]
    head = ' & '.join(', '.join(g(v) for v in c) if c is not None else 'val loss' for c in cols)
    names = ', '.join(AXIS_LABEL.get(a, tex(a)) for a in axes)
    lines = [f'\\textbf{{{tex(method)}}}' + (f' (columns: {names})' if axes else ''),
             '', '\\begin{tabular}{@{}l' + 'r' * len(cols) + '@{}}', '\\toprule',
             'lr & ' + head + ' \\\\', '\\midrule']
    for lr in lrs:
        cells = []
        for c in cols:
            hit = [x for x in grid if x['hp']['lr'] == lr and (not axes or key(x) == c)]
            cells.append(f"{hit[0]['val_loss']:.4f} ({hit[0]['best_epoch']:g})" if hit else '')
        lines.append(f'{g(lr)} & ' + ' & '.join(cells) + ' \\\\')
    lines += ['\\bottomrule', '\\end{tabular}', '', '\\medskip', '']
    return lines


def grids(res):
    L = ['% generated by analysis/p1_latex_tables.py; do not edit by hand', '']
    for key in ('xs_r16', 'xs_r1', 's_r16'):
        arm = res['arms'].get(key)
        if not arm:
            continue
        L += [f'\\subsection*{{{ARM_LABEL[key]}}}', '',
              'Tuning-seed validation loss at the best checkpoint for every grid point, with the epoch of that '
              'checkpoint in parentheses; the winner is the minimum. Rows: learning rate; columns: the second axis.',
              '', '\\footnotesize', '']
        for m in sorted(arm['methods']):
            gr = arm['methods'][m]['grid']
            if gr:
                L += grid_table(m, gr)
        L += ['\\normalsize', '']
    return '\n'.join(L) + '\n'


def sensitivity(res):
    L = ['% generated by analysis/p1_latex_tables.py; do not edit by hand', '']
    for e in res.get('sensitivity', []):
        label = STEM_LABEL.get(e['label'], e['label'])
        L += [f"\\subsection*{{{tex(label).replace(' x ', ' $\\times$ ')} --- tag \\texttt{{{tex(e['tag'])}}}: {tex(e['note'])}}}", '']
        rows = []
        for m, d in sorted(e['methods'].items()):
            winner = hp(d['winner'])
            fin = f"{d['test_loss']:.4f}" + (f" $\\pm$ {d['test_loss_sd']:.4f}" if d['test_loss_sd'] else '') \
                if d['n_finals'] else '--'
            pre = d.get('pre_registered')
            prehp = ('same' if pre['winner'] == d['winner'] else hp(pre['winner'])) if pre else '--'
            pret = f"{pre['test_loss']:.4f} ($n$={pre['n_finals']})" if pre else '--'
            rows.append(f"{tex(m)} & {winner} & {d['tune_val_loss']:.4f} & {d['n_finals']} & {fin} & {prehp} & {pret} \\\\")
        L += ['\\footnotesize', '\\resizebox{\\textwidth}{!}{%', '\\begin{tabular}{@{}lllrlll@{}}', '\\toprule',
              'Method & winner & tuning val & $n$ & test loss & registered winner & registered test \\\\',
              '\\midrule'] + rows + ['\\bottomrule', '\\end{tabular}}', '\\normalsize', '']
        if e.get('standard_vs_pre'):
            s = e['standard_vs_pre']
            seeds = ', '.join(str(x) for x in s['seeds'])
            if s['same_winner']:
                L += [f"The AdamW winner is the registered one; its finals on seeds {seeds} are the registered runs.", '']
            else:
                L += [f"Tagged AdamW against the pre-registered AdamW, paired on seeds {seeds}: difference "
                      f"${s['diff']:+.4f}$, bootstrap CI95 $[{s['boot_ci'][0]:+.4f}, {s['boot_ci'][1]:+.4f}]$, "
                      f"$p = {s['p']:.3f}$ (the winner moved).", '']
        if e.get('contrasts'):
            L += [f"Contrasts against the {e['standard']} AdamW ($n = {e['standard_desc']['n_finals']}$):", '',
                  '\\footnotesize', '\\begin{tabular}{@{}lrrrcrr@{}}', '\\toprule',
                  'Method & mean & sd & diff & bootstrap CI95 & $p$ & $p$ (Holm) \\\\', '\\midrule']
            for r in sorted(e['contrasts'], key=lambda r: r['diff']):
                L.append(f"{tex(r['method'])} & {r['mean']:.4f} & {r['sd']:.4f} & ${r['diff']:+.4f}$ & "
                         f"$[{r['boot_ci'][0]:+.4f}, {r['boot_ci'][1]:+.4f}]$ & {r['p']:.3f} & {r['p_holm']:.3f} \\\\")
            L += ['\\bottomrule', '\\end{tabular}', '\\normalsize', '']
        grids_here = {m: d['grid'] for m, d in e['methods'].items() if d['grid']}
        if grids_here:
            L += ['\\footnotesize', '\\noindent']
            for m, gr in sorted(grids_here.items()):
                L += grid_table(m, gr)
            L += ['\\normalsize', '']
    if len(L) == 2:
        L.append('No post-registration runs were found when this file was generated.')
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--analysis', default='results/p1_analysis.json')
    ap.add_argument('--out', default='paper/jmlr/generated')
    args = ap.parse_args()
    res = json.load(open(args.analysis))
    os.makedirs(args.out, exist_ok=True)
    open(os.path.join(args.out, 'grids.tex'), 'w').write(grids(res))
    open(os.path.join(args.out, 'sensitivity.tex'), 'w').write(sensitivity(res))
    print(f'[written] {args.out}/grids.tex {args.out}/sensitivity.tex')


if __name__ == '__main__':
    main()
