"""Analysis of protocol P4 (protocols/P4_cwd_size.md), fixed before the runs.

    python analysis/p4_analysis.py [--out results/p4_analysis.json] [--tex paper/jmlr/generated/p4.tex]

H6: paired CWD - AdamW at M (124.5M parameters, arm R16) over seeds 2001-2006; two-sided t-test and
t CI95. Held-out estimate: the same difference on seeds 2004-2006 alone (not a test). Descriptive:
sign-agreement fraction and total decay, L2 norm and largest absolute decayed weight at the end of
training, best validation loss at each decay on the tuning seed.
"""
import argparse
import json
import os

import numpy as np
from scipy import stats

STEM = 'M_D10M_E16'
SEEDS = [str(s) for s in range(2001, 2007)]
HELD_OUT = SEEDS[3:]


def t_interval(d):
    d = np.asarray(d)
    half = stats.t.ppf(0.975, len(d) - 1) * d.std(ddof=1) / np.sqrt(len(d))
    return [float(d.mean() - half), float(d.mean() + half)]


def arm(method):
    r = json.load(open(f'results/dc/{STEM}_{method}_p4.json'))
    fin = [r['finals'][s] for s in SEEDS]
    test = [f['test_loss'] for f in fin]
    agree = float(np.mean([e['agree'] for f in fin for e in f['curve'] if e.get('agree') is not None]))
    by_wd = {}
    for g in r['grid']:
        wd = g['hp']['wd']
        if wd not in by_wd or g['val_loss'] < by_wd[wd][1]:
            by_wd[wd] = (g['hp']['lr'], g['val_loss'])
    return {'winner': r['winner']['hp'], 'edge': r['winner']['edge'], 'tune_val': r['winner']['val_loss'],
            'test': test, 'mean': float(np.mean(test)), 'sd': float(np.std(test, ddof=1)),
            'agree': agree, 'total_decay': agree * r['winner']['hp']['wd'] if method == 'CWD' else r['winner']['hp']['wd'],
            'l2_end': float(np.mean([f['curve'][-1]['l2'] for f in fin])),
            'max_abs_end': float(np.mean([f['curve'][-1]['max_abs'] for f in fin])),
            'best_val_by_wd': {str(k): {'lr': v[0], 'val': v[1]} for k, v in sorted(by_wd.items())},
            'n_grid': len(r['grid'])}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default='results/p4_analysis.json')
    ap.add_argument('--tex', default='paper/jmlr/generated/p4.tex')
    args = ap.parse_args()
    a, c = arm('AdamW'), arm('CWD')
    d = np.array(c['test']) - np.array(a['test'])
    t = stats.ttest_1samp(d, 0.0)
    ci = t_interval(d)
    h = d[len(SEEDS) - len(HELD_OUT):]
    out = {'AdamW': a, 'CWD': c,
           'H6': {'seeds': [int(s) for s in SEEDS], 'diff': d.tolist(), 'diff_mean': float(d.mean()),
                  'diff_sd': float(d.std(ddof=1)), 't_ci': ci, 't': float(t.statistic), 'p': float(t.pvalue),
                  'cwd_lower_on': int((d < 0).sum()), 'confirmed': bool(t.pvalue < 0.05 and ci[1] < 0)},
           'held_out': {'seeds': [int(s) for s in HELD_OUT], 'diff_mean': float(h.mean()), 't_ci': t_interval(h)}}
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    json.dump(out, open(args.out, 'w'), indent=1)

    L = ['% generated by analysis/p4_analysis.py; do not edit by hand',
         '\\begin{tabular}{@{}llrrrrrr@{}}', '\\toprule',
         'Method & Winner (lr, wd) & Test loss (sd) & Agreement & Total decay & L2 norm & $\\max|w|$ & '
         'Best validation loss by decay \\\\', '\\midrule']
    for name, r in (('AdamW', a), ('CWD', c)):
        vals = ', '.join(f"{float(k):g}: {v['val']:.3f}" for k, v in r['best_val_by_wd'].items())
        L.append(f"{name} & {r['winner']['lr']:g}, {r['winner']['wd']:g} & {r['mean']:.3f} ({r['sd']:.3f}) & "
                 f"{r['agree']:.2f} & {r['total_decay']:.2f} & {r['l2_end']:.1f} & {r['max_abs_end']:.2f} & {vals} \\\\")
    h6, ho = out['H6'], out['held_out']
    L += ['\\midrule',
          f"\\multicolumn{{8}}{{@{{}}l}}{{CWD $-$ AdamW, seeds 2001--2006: ${h6['diff_mean']:+.3f}$ nats, $t$ CI95 "
          f"$[{h6['t_ci'][0]:+.3f}, {h6['t_ci'][1]:+.3f}]$, $t_5 = {h6['t']:.2f}$, $p = {h6['p']:.3f}$; "
          f"seeds 2004--2006 alone: ${ho['diff_mean']:+.3f}$ $[{ho['t_ci'][0]:+.3f}, {ho['t_ci'][1]:+.3f}]$}} \\\\",
          '\\bottomrule', '\\end{tabular}', '']
    os.makedirs(os.path.dirname(args.tex), exist_ok=True)
    open(args.tex, 'w').write('\n'.join(L))
    print(json.dumps({k: ({kk: vv for kk, vv in v.items() if kk != 'test'} if k in ('AdamW', 'CWD') else v)
                      for k, v in out.items()}, indent=1))


if __name__ == '__main__':
    main()
