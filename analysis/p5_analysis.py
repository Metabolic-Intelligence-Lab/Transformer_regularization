"""Analysis of protocols P5 (protocols/P5_cwd_355M.md) and P5x (protocols/P5x_edges_355M.md).

    python analysis/p5_analysis.py [--out results/p5_analysis.json] [--tex paper/jmlr/generated/p5.tex]

H7: paired CWD - AdamW at L (354.9M parameters, arm R16) over seeds 3001-3006; two-sided t-test and
t CI95. Descriptive: sign-agreement fraction and total decay, L2 norm and largest absolute decayed
weight at the end of training, best-checkpoint epoch, best validation loss at each decay on the tuning
seed, and the contrasts at 51.5M (P2, H1), 124.5M (P4, H6) and 355M side by side. P5x: the extended
grids, whether each winner moved, and the hardware check (CWD seed 3001 on an RTX 4090).
"""
import argparse
import json
import os

import numpy as np
from scipy import stats

STEM = 'L_D10M_E16'
SEEDS = [str(s) for s in range(3001, 3007)]


def t_interval(d):
    d = np.asarray(d)
    half = stats.t.ppf(0.975, len(d) - 1) * d.std(ddof=1) / np.sqrt(len(d))
    return [float(d.mean() - half), float(d.mean() + half)]


def sci(p):
    m, e = f'{p:.1e}'.split('e')
    return f'{m} \\times 10^{{{int(e)}}}'


def load(method, tag):
    return json.load(open(f'results/dc/{STEM}_{method}_{tag}.json'))


def best_by_wd(grid):
    by_wd = {}
    for g in grid:
        wd = g['hp']['wd']
        if wd not in by_wd or g['val_loss'] < by_wd[wd][1]:
            by_wd[wd] = (g['hp']['lr'], g['val_loss'])
    return {str(k): {'lr': v[0], 'val': v[1]} for k, v in sorted(by_wd.items())}


def arm(method):
    r = load(method, 'p5')
    fin = [r['finals'][s] for s in SEEDS]
    test = [f['test_loss'] for f in fin]
    agree = float(np.mean([e['agree'] for f in fin for e in f['curve'] if e.get('agree') is not None]))
    wd = r['winner']['hp']['wd']
    return {'winner': r['winner']['hp'], 'edge': r['winner']['edge'], 'tune_val': r['winner']['val_loss'],
            'test': test, 'mean': float(np.mean(test)), 'sd': float(np.std(test, ddof=1)),
            'agree': agree, 'total_decay': agree * wd if method == 'CWD' else wd,
            'l2_end': float(np.mean([f['curve'][-1]['l2'] for f in fin])),
            'max_abs_end': float(np.mean([f['curve'][-1]['max_abs'] for f in fin])),
            'best_epoch': float(np.mean([f['best_epoch'] for f in fin])),
            'best_val_by_wd': best_by_wd(r['grid']), 'n_grid': len(r['grid'])}


def extension(method, p5_winner):
    r = load(method, 'p5x')
    p5_points = {(g['hp']['lr'], g['hp']['wd']) for g in load(method, 'p5')['grid']}
    new = [{'lr': g['hp']['lr'], 'wd': g['hp']['wd'], 'val': g['val_loss']} for g in r['grid']
           if (g['hp']['lr'], g['hp']['wd']) not in p5_points]
    return {'new_points': new, 'winner': r['winner']['hp'], 'edge': r['winner']['edge'],
            'moved': r['winner']['hp'] != p5_winner, 'best_val_by_wd': best_by_wd(r['grid'])}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default='results/p5_analysis.json')
    ap.add_argument('--tex', default='paper/jmlr/generated/p5.tex')
    args = ap.parse_args()
    a, c = arm('AdamW'), arm('CWD')
    d = np.array(c['test']) - np.array(a['test'])
    t = stats.ttest_1samp(d, 0.0)
    ci = t_interval(d)
    h7 = {'seeds': [int(s) for s in SEEDS], 'diff': d.tolist(), 'diff_mean': float(d.mean()),
          'diff_sd': float(d.std(ddof=1)), 't_ci': ci, 't': float(t.statistic), 'p': float(t.pvalue),
          'cwd_lower_on': int((d < 0).sum()), 'confirmed': bool(t.pvalue < 0.05 and ci[1] < 0)}

    xa, xc = extension('AdamW', a['winner']), extension('CWD', c['winner'])
    hw = load('CWD', 'p5hw')
    hw_test = hw['finals']['3001']['test_loss']
    hardware = {'cwd_3001_rtx4090': hw_test, 'cwd_3001_rtx3090': c['test'][0],
                'gpu_diff': hw_test - c['test'][0],
                'same_gpu_diff_3001': hw_test - a['test'][0], 'mixed_gpu_diff_3001': float(d[0])}

    p2 = json.load(open('results/p2_analysis.json'))['H1']
    p4 = json.load(open('results/p4_analysis.json'))['H6']
    sizes = [{'size': '51.5M', 'protocol': 'P2 (H1)', 'diff_mean': p2['diff_mean'], 't_ci': p2['t_ci'], 'p': p2['p']},
             {'size': '124.5M', 'protocol': 'P4 (H6)', 'diff_mean': p4['diff_mean'], 't_ci': p4['t_ci'], 'p': p4['p']},
             {'size': '354.9M', 'protocol': 'P5 (H7)', 'diff_mean': h7['diff_mean'], 't_ci': h7['t_ci'], 'p': h7['p']}]

    out = {'AdamW': a, 'CWD': c, 'H7': h7, 'P5x': {'AdamW': xa, 'CWD': xc, 'hardware': hardware},
           'sizes': sizes}
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    json.dump(out, open(args.out, 'w'), indent=1)

    L = ['% generated by analysis/p5_analysis.py; do not edit by hand',
         '\\begin{tabular}{@{}llrrrrrr@{}}', '\\toprule',
         'Method & Winner (lr, wd) & Test loss (sd) & Agreement & Total decay & L2 norm & $\\max|w|$ & '
         'Best validation loss by decay \\\\', '\\midrule']
    for name, r, x in (('AdamW', a, xa), ('CWD', c, xc)):
        vals = ', '.join(f"{float(k):g}: {v['val']:.3f}" for k, v in x['best_val_by_wd'].items())
        L.append(f"{name} & {r['winner']['lr']:g}, {r['winner']['wd']:g} & {r['mean']:.3f} ({r['sd']:.3f}) & "
                 f"{r['agree']:.2f} & {r['total_decay']:.2f} & {r['l2_end']:.1f} & {r['max_abs_end']:.2f} & {vals} \\\\")
    L += ['\\midrule',
          f"\\multicolumn{{8}}{{@{{}}l}}{{CWD $-$ AdamW, seeds 3001--3006: ${h7['diff_mean']:+.3f}$ nats, $t$ CI95 "
          f"$[{h7['t_ci'][0]:+.3f}, {h7['t_ci'][1]:+.3f}]$, $t_5 = {h7['t']:.2f}$, $p = {sci(h7['p'])}$; "
          f"CWD lower on {h7['cwd_lower_on']} of 6 seeds}} \\\\",
          f"\\multicolumn{{8}}{{@{{}}l}}{{Same contrast at 51.5M (P2): ${p2['diff_mean']:+.3f}$ "
          f"$[{p2['t_ci'][0]:+.3f}, {p2['t_ci'][1]:+.3f}]$; at 124.5M (P4): ${p4['diff_mean']:+.3f}$ "
          f"$[{p4['t_ci'][0]:+.3f}, {p4['t_ci'][1]:+.3f}]$}} \\\\",
          '\\bottomrule', '\\end{tabular}', '']
    os.makedirs(os.path.dirname(args.tex), exist_ok=True)
    open(args.tex, 'w').write('\n'.join(L))
    print(json.dumps({k: ({kk: vv for kk, vv in v.items() if kk != 'test'} if k in ('AdamW', 'CWD') else v)
                      for k, v in out.items()}, indent=1))


if __name__ == '__main__':
    main()
