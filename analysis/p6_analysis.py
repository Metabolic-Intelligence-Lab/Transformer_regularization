"""Analysis of protocol P6 (protocols/P6_cwd_124M_seeds.md), fixed before the runs.

    python analysis/p6_analysis.py [--out results/p6_analysis.json] [--tex paper/jmlr/generated/p6.tex]

H8: paired CWD - AdamW at M (124.5M parameters, arm R16) over the new seeds 2007-2024 (blocks A, B, C,
tags p6a, p6b, p6c); two-sided t-test and t CI95. Secondary estimate (not a test): the same difference
over the 24 seeds 2001-2024, P4 and P6 together. Descriptive: seeds on which CWD is lower, agreement
fraction, total decay, L2 norm and largest absolute decayed weight at the end of training, block means.
"""
import argparse
import json
import os

import numpy as np
from scipy import stats

STEM = 'M_D10M_E16'
BLOCKS = {'A': 'p6a', 'B': 'p6b', 'C': 'p6c'}
P4_SEEDS = [str(s) for s in range(2001, 2007)]


def t_test(d):
    d = np.asarray(d)
    half = stats.t.ppf(0.975, len(d) - 1) * d.std(ddof=1) / np.sqrt(len(d))
    t = stats.ttest_1samp(d, 0.0)
    return {'n': len(d), 'diff_mean': float(d.mean()), 'diff_sd': float(d.std(ddof=1)),
            't_ci': [float(d.mean() - half), float(d.mean() + half)], 't': float(t.statistic),
            'p': float(t.pvalue), 'cwd_lower_on': int((d < 0).sum())}


def finals(method, tag):
    r = json.load(open(f'results/dc/{STEM}_{method}_{tag}.json'))
    return r['winner']['hp'], r['finals']


def arm(method):
    """All P6 finals of one method, keyed by seed, with the block of each seed."""
    out, hp = {}, None
    for block, tag in BLOCKS.items():
        hp, fin = finals(method, tag)
        for seed, f in fin.items():
            out[seed] = dict(f, block=block)
    return hp, dict(sorted(out.items()))


def describe(hp, fin, method):
    vals = list(fin.values())
    test = [f['test_loss'] for f in vals]
    agree = float(np.mean([e['agree'] for f in vals for e in f['curve'] if e.get('agree') is not None]))
    return {'winner': hp, 'mean': float(np.mean(test)), 'sd': float(np.std(test, ddof=1)), 'agree': agree,
            'total_decay': agree * hp['wd'] if method == 'CWD' else hp['wd'],
            'l2_end': float(np.mean([f['curve'][-1]['l2'] for f in vals])),
            'max_abs_end': float(np.mean([f['curve'][-1]['max_abs'] for f in vals])),
            'best_epoch': float(np.mean([f['best_epoch'] for f in vals]))}


def sci(p):
    if p >= 0.001:
        return f'{p:.3f}'
    m, e = f'{p:.1e}'.split('e')
    return f'{m} \\times 10^{{{int(e)}}}'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default='results/p6_analysis.json')
    ap.add_argument('--tex', default='paper/jmlr/generated/p6.tex')
    args = ap.parse_args()
    hp_a, fa = arm('AdamW')
    hp_c, fc = arm('CWD')
    assert list(fa) == list(fc) == [str(s) for s in range(2007, 2025)], 'P6 needs seeds 2007-2024 for both'
    seeds = list(fa)
    d = np.array([fc[s]['test_loss'] - fa[s]['test_loss'] for s in seeds])
    h8 = t_test(d)
    h8.update(seeds=[int(s) for s in seeds], diff=d.tolist(), confirmed=bool(h8['p'] < 0.05 and h8['t_ci'][1] < 0),
              cwd_loses=bool(h8['p'] < 0.05 and h8['t_ci'][0] > 0))
    blocks = {b: t_test([d[i] for i, s in enumerate(seeds) if fa[s]['block'] == b]) for b in BLOCKS}

    p4_all = json.load(open('results/p4_analysis.json'))
    p4 = p4_all['H6']
    pooled = t_test(list(p4['diff']) + d.tolist())
    out = {'AdamW': describe(hp_a, fa, 'AdamW'), 'CWD': describe(hp_c, fc, 'CWD'), 'H8': h8, 'blocks': blocks,
           'pooled_P4_P6': dict(pooled, seeds='2001-2024', note='estimate, not a test; P4 seeds seen before P6'),
           'P4_H6': {k: p4[k] for k in ('diff_mean', 't_ci', 'p')}}
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    json.dump(out, open(args.out, 'w'), indent=1)

    a, c = out['AdamW'], out['CWD']
    L = ['% generated by analysis/p6_analysis.py; do not edit by hand',
         '\\begin{tabular}{@{}lrrrrrrr@{}}', '\\toprule',
         'Seeds & $n$ & AdamW & CWD & CWD $-$ AdamW & $t$ CI95 & $p$ & CWD lower \\\\', '\\midrule']
    for name, r, extra in (('2001--2006 (P4)', p4 | {'n': 6, 'cwd_lower_on': int(np.sum(np.array(p4['diff']) < 0))}, (f"{p4_all['AdamW']['mean']:.3f}", f"{p4_all['CWD']['mean']:.3f}")),
                           ('2007--2024 (P6, H8)', h8, (f"{a['mean']:.3f}", f"{c['mean']:.3f}")),
                           ('2001--2024 (pooled)', pooled, ('', ''))):
        L.append(f"{name} & {r['n']} & {extra[0]} & {extra[1]} & ${r['diff_mean']:+.3f}$ & "
                 f"$[{r['t_ci'][0]:+.3f}, {r['t_ci'][1]:+.3f}]$ & ${sci(r['p'])}$ & {r['cwd_lower_on']} \\\\")
    L += ['\\bottomrule', '\\end{tabular}', '']
    os.makedirs(os.path.dirname(args.tex), exist_ok=True)
    open(args.tex, 'w').write('\n'.join(L))
    print(json.dumps({k: v for k, v in out.items()}, indent=1))


if __name__ == '__main__':
    main()
