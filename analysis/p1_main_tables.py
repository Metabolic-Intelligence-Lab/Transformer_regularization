"""Main-text tables of the JMLR manuscript (Tables 2-5), from results/p1_analysis.json.

    python analysis/p1_main_tables.py [--analysis results/p1_analysis.json] [--out paper/jmlr/generated]

Writes tab_xs_r16.tex, tab_xs_r1.tex, tab_regime.tex and tab_s.tex (tabular environments only;
main.tex holds the captions). Intervals are t-based CI95 of the paired difference (Welch for the
regime effect); the verdict column is the pre-registered one (Holm, then TOST at 0.01 nats).
"""
import argparse
import json
import os

AXIS = {'wd': 'wd', 'rho': '$\\rho$', 'delta': '$\\delta$', 'ema': 'ema', 'dropout': 'dropout', 'warm_start': 'warm start'}


def g(v):
    return f'{v:g}'


def winner(hp):
    keys = [k for k in hp if k not in ('aux_lr', 'aux_wd')]
    return ', '.join(('lr ' if k == 'lr' else AXIS.get(k, k) + ' ') + g(hp[k]) for k in keys)


def ci(c):
    return f"$[{c[0]:+.3f}, {c[1]:+.3f}]$"


def contrast_table(arm, extra=False):
    meth, rows = arm['methods'], arm['contrasts_best']
    std = meth['AdamW']
    head = 'Method & mean & sd & diff & t CI95 & $p$ & $p$ (Holm) & verdict & winner'
    cols = '@{}lrrrcrrll@{}'
    if extra:
        head = 'Method & mean & sd & diff & t CI95 & $p$ & $p$ (Holm) & verdict & best epoch & final-ckpt loss'
        cols = '@{}lrrrcrrlrr@{}'
    L = ['% generated by analysis/p1_main_tables.py; do not edit by hand', f'\\begin{{tabular}}{{{cols}}}',
         '\\toprule', head + ' \\\\', '\\midrule']
    entries = sorted(rows + [dict(method='AdamW', diff=0.0, std=True)], key=lambda r: r['diff'])
    for r in entries:
        m = meth[r['method']]
        sd = f"{m['test_loss_sd']:.3f}" if m['n_finals'] > 1 else '--'
        tail = (f" & {m['best_epoch']:.1f} & {m['final_test_loss']:.2f}" if extra else f" & {winner(m['winner'])}")
        if r.get('std'):
            L.append(f"\\textbf{{AdamW}} & {m['test_loss']:.3f} & {sd} & & & & & standard{tail} \\\\")
        else:
            L.append(f"{r['method']} & {m['test_loss']:.3f} & {sd} & ${r['diff']:+.3f}$ & {ci(r['t_ci'])} & "
                     f"{r['p']:.3f} & {r['p_holm']:.3f} & {r['verdict']}{tail} \\\\")
    L += ['\\bottomrule', '\\end{tabular}', '']
    return '\n'.join(L)


def regime_table(res):
    L = ['% generated by analysis/p1_main_tables.py; do not edit by hand', '\\begin{tabular}{@{}lrrrc@{}}',
         '\\toprule', 'Method & diff R16 & diff R1 & regime effect & Welch t CI95 \\\\', '\\midrule']
    for r in sorted(res['regime_effect'], key=lambda r: r['regime_effect']):
        L.append(f"{r['method']} & ${r['diff_r16']:+.3f}$ & ${r['diff_r1']:+.3f}$ & ${r['regime_effect']:+.3f}$ & "
                 f"{ci(r['t_ci'])} \\\\")
    L += ['\\bottomrule', '\\end{tabular}', '']
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--analysis', default='results/p1_analysis.json')
    ap.add_argument('--out', default='paper/jmlr/generated')
    args = ap.parse_args()
    res = json.load(open(args.analysis))
    os.makedirs(args.out, exist_ok=True)
    files = {'tab_xs_r16.tex': contrast_table(res['arms']['xs_r16']),
             'tab_xs_r1.tex': contrast_table(res['arms']['xs_r1']),
             'tab_regime.tex': regime_table(res),
             'tab_s.tex': contrast_table(res['arms']['s_r16'], extra=True)}
    for name, text in files.items():
        open(os.path.join(args.out, name), 'w').write(text)
    print('[written]', ' '.join(files))


if __name__ == '__main__':
    main()
